// english/actions-map.js — Phase 4-A: 영어 액션 등록표
TutorActions.register({
  'unlock': () => unlockApp(),
  'open-settings': () => openSettings(),
  'toggle-dark-mode': () => toggleDarkMode(),
  'open-history': (el) => openHistoryModal(el.dataset.tab || 'wordbook'),
  'change-theme': (el) => changeTheme(el.dataset.theme),
  'model-change': () => onModelChange(),
  'switch-mode': (el) => switchMode(el.dataset.mode),
  'quiz-generate': (el) => { switchMode('quiz'); generateEnglishQuiz(el.dataset.force === '1'); },
  'pick-image': (el, event) => { const i = document.getElementById('fileInput'); if (!i || event.target === i) return; i.click(); },
  'image-upload': (el, event) => handleImageUpload(event),
  'clear-image': () => clearImage(),
  'analyze': () => analyzeEnglishProblem(),
  'play-speech': () => playEnglishSpeech(),
  'stop-speech': () => stopAllSpeech(),
  'save-lesson-history': () => saveCurrentLessonToHistory(),
  'generate-quiz': (el) => generateEnglishQuiz(el.dataset.force === '1'),
  'speak-question': () => speakQuizQuestion(),
  'toggle-quiz-hint': () => toggleQuizHint(),
  'submit-quiz': () => submitEnglishQuizAnswer(),
  'writing-prompt': () => generateWritingPrompt(),
  'word-count': () => updateWordCount(),
  'submit-writing': () => submitWritingForCorrection(),
  'close-history': () => closeHistoryModal(),
  'history-tab': (el) => switchHistoryTab(el.dataset.tab),
  'render-wordbook': () => renderWordbookList(),
  'open-custom-word': () => openAddCustomWord(),
  'close-custom-word': () => document.getElementById('customWordForm')?.classList.add('hidden'),
  'save-custom-word': () => saveCustomWord(),
  'clear-history-tab': () => clearCurrentHistoryTab(),
  'close-settings': () => closeSettings(),
  'save-settings': () => saveSettings(),
  'speak-en': (el) => speakEnglishText(el.dataset.text),
  'save-all-words': () => saveAllLessonWords(),
  'add-word-index': (el) => addWordToWordbook(Number(el.dataset.idx)),
  'select-quiz-choice': (el) => selectEnglishQuizChoice(Number(el.dataset.idx)),
  'speak-quiz-sentence': (el) => speakQuizFullSentence(el.dataset.text),
  'save-quiz-record': (el) => saveQuizRecordToHistory(el.dataset.correct === '1'),
  'add-word-direct': (el) => addWordDirect(el.dataset.word, el.dataset.meaning, el.dataset.example || ''),
  'save-writing-history': () => saveWritingToHistory(),
  'unblur': (el) => el.classList.remove('blur-sm'),
  'toggle-memorized': (el) => toggleWordMemorized(el.dataset.id),
  'delete-word': (el) => deleteWordItem(el.dataset.id),
  'restore-history-item': (el) => restoreHistoryItem(el.dataset.id),
  'delete-history-item': (el) => deleteHistoryItem(el.dataset.id)
});
